"""gen_props.py <settings-map.json> <items.json> <out nlr_props.h> [body]: the SDK's table of the
camera's settings by name.

The loader reads and watches settings by store item id (prop_get,
prop_watch); a program names them. This turns the settings map the firmware
study made (every menu item, the store item it lives in and the raw code
of each choice) into a header with no
pointers in it -- names and labels are offsets into one string blob -- so a
program carries it without relocations. Only entries the study trusts are
taken (confirmed, observed, decoded, mapped). items.json (the same study)
gives each item's type tag: the camera's settings service acts on a write
only when the id carries it (0x07000510 for white balance, not 0x0510), so
prop_set needs nlr_prop_tagged(). A dev tool: the header it writes is what
programs include; nothing on the camera runs Python."""
import hashlib
import json
import sys

TRUST = {"confirmed", "observed", "decoded", "mapped"}
TYPES = {"u8": 1, "u16": 2, "u32": 3, "s8": 4, "s16": 5, "s32": 6, "blob": 7}

src, items_src, dst = sys.argv[1], sys.argv[2], sys.argv[3]
# The body the map describes, for the header's comment: the Z 6III by default
# (sdk/nlr_props.h); "Z 8 C3.11" for the map z8_settings.py reads from the
# Z 8's own tables (sdk/z8/nlr_props.h).
body = sys.argv[4] if len(sys.argv) > 4 else "Z 6III 2.00"
raw = open(src, "rb").read()
smap = json.loads(raw)
tags = {int(k, 16): v.get("tag") for k, v in json.load(open(items_src))["items"].items()
        if isinstance(v.get("tag"), int)}
text = bytearray(b"\0")
offsets = {}


def string(s):
    b = s.encode("utf-8")
    if b not in offsets:
        offsets[b] = len(text)
        text.extend(b + b"\0")
    return offsets[b]


entries = []
for e in smap:
    if e.get("status") not in TRUST:
        continue
    store = e.get("store") or {}
    for n, (sid, s) in enumerate(store.items()):
        name = e["id"] if n == 0 else "%s#%d" % (e["id"], n)
        codes = []
        for code, label in (s.get("codes") or {}).items():
            try:
                value = int(code, 0) & 0xffffffff
            except ValueError:
                continue
            # codes are 32-bit words; the map writes some as 64-bit negatives
            if value >= 0x80000000:
                value -= 1 << 32
            if label and not label.startswith("("):
                codes.append((value, label))
        entries.append((name, int(sid, 16), int(s.get("size") or 0),
                        TYPES.get(s.get("type"), 0), e.get("en") or "", codes))

entries.sort(key=lambda x: x[0].encode())
rows, choices = [], []
for name, item, size, kind, label, codes in entries:
    first = len(choices)
    for value, clabel in codes:
        choices.append((value, string(clabel)))
    rows.append((string(name), item, min(size, 0xffff), kind, string(label), first, len(codes),
                 tags.get(item, 0)))

out = []
out.append("/* generated by sdk/tools/gen_props.py from settings-map.json")
out.append(" * (sha256 %s) -- do not edit */" % hashlib.sha256(raw).hexdigest()[:16])
out.append("#ifndef NLR_PROPS_H")
out.append("#define NLR_PROPS_H")
out.append("")
out.append("#include <stdint.h>")
out.append("")
out.append("/* One setting of the %s: its name (the settings map's id), the" % body)
out.append(" * store item that holds it, its size and type, its English label, and")
out.append(" * its choices (raw code and label). Names and labels are offsets into")
out.append(" * nlr_props_text, so the table carries no pointers. */")
out.append("#define NLR_PT_U8 1")
out.append("#define NLR_PT_U16 2")
out.append("#define NLR_PT_U32 3")
out.append("#define NLR_PT_S8 4")
out.append("#define NLR_PT_S16 5")
out.append("#define NLR_PT_S32 6")
out.append("#define NLR_PT_BLOB 7")
out.append("struct nlr_prop_name {")
out.append("    uint32_t name;      /* offset into nlr_props_text */")
out.append("    uint16_t id;        /* store item, for prop_get and prop_watch */")
out.append("    uint16_t size;")
out.append("    uint8_t type;       /* NLR_PT_*, 0 unknown */")
out.append("    uint8_t tag;        /* the settings service's type tag; 0: never written */")
out.append("    uint16_t choice_count;")
out.append("    uint32_t label;     /* offset into nlr_props_text */")
out.append("    uint32_t first_choice;")
out.append("};")
out.append("struct nlr_prop_choice {")
out.append("    int32_t code;")
out.append("    uint32_t label;")
out.append("};")
out.append("")
out.append("#define NLR_PROP_NAMES %d" % len(rows))
out.append("static const struct nlr_prop_name nlr_prop_names[NLR_PROP_NAMES] = {")
for r in rows:
    out.append("    { %d, 0x%04x, %d, %d, %d, %d, %d, %d }," % (r[0], r[1], r[2], r[3], r[7], r[6], r[4], r[5]))
out.append("};")
out.append("static const struct nlr_prop_choice nlr_prop_choices[%d] = {" % max(1, len(choices)))
for c in choices:
    code = "(-2147483647 - 1)" if c[0] == -(1 << 31) else str(c[0])
    out.append("    { %s, %d }," % (code, c[1]))
if not choices:
    out.append("    { 0, 0 },")
out.append("};")
out.append("static const char nlr_props_text[%d] =" % (len(text)))
blob = bytes(text)
for i in range(0, len(blob), 64):
    chunk = blob[i:i + 64]
    out.append('    "' + "".join("\\%03o" % b if b < 0x20 or b > 0x7e or b in (0x22, 0x5c, 0x3f) else chr(b) for b in chunk) + '"')
out.append("    ;")
out.append("")
# Every item the firmware study found a tag for (items.json), by id: the
# settings above are a subset; an item not named there can still be written
# by id when the camera's own code writes it with that tag.
tagged = sorted(tags.items())
out.append("/* The type tag of every item the camera's own code writes through the")
out.append(" * settings service, by id (sorted): nlr_prop_tag_of() looks one up. */")
out.append("struct nlr_prop_tag {")
out.append("    uint16_t id;")
out.append("    uint8_t tag;")
out.append("    uint8_t reserved;")
out.append("};")
out.append("#define NLR_PROP_TAGS %d" % len(tagged))
out.append("static const struct nlr_prop_tag nlr_prop_tags[NLR_PROP_TAGS] = {")
for item, tag in tagged:
    out.append("    { 0x%04x, %d, 0 }," % (item, tag))
out.append("};")
out.append("")
out.append("/* The id prop_set takes for item `id` (its tag in the top byte), or 0 when")
out.append(" * the camera's code never writes it. */")
out.append("static inline uint32_t nlr_prop_tag_of(uint16_t id)")
out.append("{")
out.append("    uint32_t lo = 0, hi = NLR_PROP_TAGS;")
out.append("    while (lo < hi) {")
out.append("        uint32_t mid = (lo + hi) / 2;")
out.append("        if (nlr_prop_tags[mid].id == id)")
out.append("            return (uint32_t)nlr_prop_tags[mid].tag << 24 | id;")
out.append("        if (nlr_prop_tags[mid].id < id)")
out.append("            lo = mid + 1;")
out.append("        else")
out.append("            hi = mid;")
out.append("    }")
out.append("    return 0;")
out.append("}")
out.append("")
out.append("static inline const char *nlr_prop_text(uint32_t offset)")
out.append("{")
out.append("    return offset < sizeof nlr_props_text ? nlr_props_text + offset : \"\";")
out.append("}")
out.append("")
out.append("/* The setting called `name`, or 0. The table is sorted by name. */")
out.append("static inline const struct nlr_prop_name *nlr_prop_find(const char *name)")
out.append("{")
out.append("    uint32_t lo = 0, hi = NLR_PROP_NAMES;")
out.append("    while (lo < hi) {")
out.append("        uint32_t mid = (lo + hi) / 2;")
out.append("        const unsigned char *a = (const unsigned char *)nlr_prop_text(nlr_prop_names[mid].name);")
out.append("        const unsigned char *b = (const unsigned char *)name;")
out.append("        while (*a && *a == *b) {")
out.append("            a++;")
out.append("            b++;")
out.append("        }")
out.append("        if (*a == *b)")
out.append("            return &nlr_prop_names[mid];")
out.append("        if (*a < *b)")
out.append("            lo = mid + 1;")
out.append("        else")
out.append("            hi = mid;")
out.append("    }")
out.append("    return 0;")
out.append("}")
out.append("")
out.append("/* The id prop_set takes: the item with its type tag, or 0 for an item")
out.append(" * the camera's menus never write (read it, watch it, do not set it). */")
out.append("static inline uint32_t nlr_prop_tagged(const struct nlr_prop_name *p)")
out.append("{")
out.append("    return p && p->tag ? (uint32_t)p->tag << 24 | p->id : 0;")
out.append("}")
out.append("")
out.append("/* The label of `code` among the setting's choices, or 0. */")
out.append("static inline const char *nlr_prop_choice_label(const struct nlr_prop_name *p, int32_t code)")
out.append("{")
out.append("    for (uint32_t n = 0; p && n < p->choice_count; n++)")
out.append("        if (nlr_prop_choices[p->first_choice + n].code == code)")
out.append("            return nlr_prop_text(nlr_prop_choices[p->first_choice + n].label);")
out.append("    return 0;")
out.append("}")
out.append("")
out.append("#endif")
open(dst, "w").write("\n".join(out) + "\n")
print("%d settings, %d choices, %d bytes of text" % (len(rows), len(choices), len(text)))
